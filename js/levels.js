/**
 * Bekantan Quest - Level Design & Tilemaps
 * Dirancang untuk STI7356 Materi Pertemuan 3 & 11:
 * - Level 1: Taman Mangrove Barito (Tutorial & Pengenalan Core Loop)
 * - Level 2: Rawa & Jeram Riam Kanan (Moving Platform & Jamur Pemantul)
 * - Level 3: Menara Konservasi Meratus (Tantangan Vertikal & Drone Musuh)
 */

class Level {
    constructor(data) {
        this.id = data.id;
        this.name = data.name;
        this.theme = data.theme; // 'mangrove', 'river', 'mountain'
        this.tileSize = 32;
        this.cols = data.map[0].length;
        this.rows = data.map.length;
        this.map = data.map;
        this.worldWidth = this.cols * this.tileSize;
        this.worldHeight = this.rows * this.tileSize;

        this.gravity = 1100;
        this.friction = 0.72;
        this.terminalVelocity = 750;

        this.spawnPoint = { x: data.spawn.x * this.tileSize, y: data.spawn.y * this.tileSize };

        // Entities arrays
        this.collectibles = (data.collectibles || []).map(c => new Collectible(c.x * this.tileSize, c.y * this.tileSize, c.type));
        this.enemies = (data.enemies || []).map(e => new Enemy(e.x * this.tileSize, e.y * this.tileSize, e.type, e.minX * this.tileSize, e.maxX * this.tileSize));
        this.movingPlatforms = (data.movingPlatforms || []).map(p => new MovingPlatform(p.x * this.tileSize, p.y * this.tileSize, p.w * this.tileSize, p.h || 18, p.moveX * this.tileSize, p.moveY * this.tileSize, p.speed));
        this.goal = new GoalShrine(data.goal.x * this.tileSize, data.goal.y * this.tileSize);

        // Spring trigger animation tracker
        this.springs = {};
    }

    getTile(col, row) {
        if (col < 0 || col >= this.cols || row < 0 || row >= this.rows) {
            return 0;
        }
        return this.map[row][col];
    }

    onSpringTrigger(col, row) {
        this.springs[`${col},${row}`] = 0.25; // 0.25s animation
    }

    update(dt) {
        for (const key in this.springs) {
            this.springs[key] -= dt;
            if (this.springs[key] <= 0) {
                delete this.springs[key];
            }
        }
    }
}

